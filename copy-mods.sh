# Copy workshop mods from one server to another via rsync over SSH.
# Usage:
#   ./copy-mods.sh user@source-host /path/to/source/workshop user@dest-host /path/to/dest/workshop
#
# The workshop dir is the one containing numbered mod folders, e.g.:
#   Steam/steamapps/workshop/content/107410/

